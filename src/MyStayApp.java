/**
 * UseCase1HotelBookingApp
 *
 * <p>This class represents the entry point of the Hotel Booking Application.
 * It demonstrates how a Java program begins execution using the main() method
 * and prints a welcome message to the console.</p>
 *
 * @author Aditya Kadam
 * @version 1.0
 */

public class MyStayApp {

    /**
     * The main method is the entry point of the Java application.
     * The JVM invokes this method when the program starts.
     *
     * @param args command line arguments
     */
    public static void main(String[] args) {

        // Display Welcome Message
        System.out.println("=====================================");
        System.out.println("      WELCOME TO HOTEL BOOKING APP   ");
        System.out.println("=====================================");

        // Display Application Details
        System.out.println("Application Name : MyStay - Hotel Booking System");
        System.out.println("Version          : 1.0");

        // Application Startup Confirmation
        System.out.println("-------------------------------------");
        System.out.println("Application Started Successfully!");
        System.out.println("Thank you for using MyStay.");
    }
}